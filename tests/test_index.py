#!/usr/bin/env python3
"""Tests for IndexPage."""

from datetime import datetime, timezone
from html.parser import HTMLParser

import pytest

from podcastify.index import IndexEntry, IndexPage

BUILT = datetime(2030, 1, 2, 3, 4, 5, tzinfo=timezone.utc)


def _entry(name="show", title="Show", episodes=3, built=BUILT, image=None):
    return IndexEntry(name=name, title=title, episode_count=episodes, built=built, image=image)


class _Collector(HTMLParser):
    def __init__(self):
        super().__init__()
        self.tags = []
        self.hrefs = []

    def handle_starttag(self, tag, attrs):
        self.tags.append(tag)
        self.hrefs += [value for key, value in attrs if key == "href"]


def _parse(html):
    collector = _Collector()
    collector.feed(html)
    return collector


class TestRender:
    def test_first_line_is_the_marker(self):
        assert IndexPage().render([_entry()]).splitlines()[0] == "<!-- generated by podcastify -->"

    def test_lists_title_feed_url_count_and_date(self):
        html = IndexPage().render([_entry(name="my show", title="My Show", episodes=3)])
        assert "<h2>My Show</h2>" in html
        assert 'href="http://localhost:8080/my%20show.xml"' in html
        assert "3 episodes" in html
        assert '<time datetime="2030-01-02T03:04:05+00:00">2030-01-02</time>' in html

    def test_single_episode_is_singular(self):
        assert "1 episode," in IndexPage().render([_entry(episodes=1)])

    def test_missing_build_date_is_left_out(self):
        html = IndexPage().render([_entry(built=None)])
        assert "<time" not in html
        assert "3 episodes" in html

    def test_feed_url_is_percent_encoded_like_the_feed(self):
        html = IndexPage().render([_entry(name="café &1")])
        assert 'href="http://localhost:8080/caf%C3%A9%20%261.xml"' in html

    def test_base_url_is_used(self, monkeypatch):
        monkeypatch.setattr("podcastify.config.Config.BASE_URL", "https://pods.example.com")
        assert 'href="https://pods.example.com/show.xml"' in IndexPage().render([_entry()])

    def test_cover_image_is_shown_when_present(self):
        html = IndexPage().render([_entry(image="http://localhost:8080/show/cover.jpg")])
        assert '<img src="http://localhost:8080/show/cover.jpg"' in html

    def test_no_cover_means_no_img(self):
        assert "<img" not in IndexPage().render([_entry()])

    def test_entries_are_ordered_by_title_ignoring_case(self):
        html = IndexPage().render([_entry("c", "charlie"), _entry("a", "Bravo"), _entry("b", "alpha")])
        assert html.index("alpha") < html.index("Bravo") < html.index("charlie")

    def test_equal_titles_fall_back_to_the_name(self):
        html = IndexPage().render([_entry("b", "Same"), _entry("a", "Same")])
        assert html.index("/a.xml") < html.index("/b.xml")

    def test_empty_state(self):
        html = IndexPage().render([])
        assert 'class="empty"' in html
        assert "<ul" not in html

    def test_hostile_title_is_escaped(self):
        html = IndexPage().render([_entry(title='<script>alert("x")</script> & "q"')])
        assert "<script" not in html
        assert "&lt;script&gt;alert(&quot;x&quot;)&lt;/script&gt; &amp; &quot;q&quot;" in html

    def test_hostile_image_url_cannot_break_out_of_the_attribute(self):
        html = IndexPage().render([_entry(image='http://x/a.jpg" onerror="alert(1)')])
        assert 'onerror="alert' not in html
        assert "&quot; onerror=&quot;alert(1)" in html

    def test_hostile_name_cannot_break_out_of_the_href(self):
        html = IndexPage().render([_entry(name='a"><script>x</script>')])
        assert "<script" not in html

    def test_no_javascript_and_no_external_resources(self):
        html = IndexPage().render([_entry(image="http://localhost:8080/show/cover.jpg")])
        parsed = _parse(html)
        assert "script" not in parsed.tags
        assert "link" not in parsed.tags
        assert "@import" not in html

    def test_is_semantic_html5_with_lang_and_viewport(self):
        html = IndexPage().render([_entry()])
        assert "<!DOCTYPE html>" in html
        assert '<html lang="en">' in html
        assert '<meta name="viewport" content="width=device-width, initial-scale=1">' in html
        assert {"main", "h1", "h2", "ul", "li"} <= set(_parse(html).tags)

    def test_supports_dark_mode(self):
        assert "prefers-color-scheme: dark" in IndexPage().render([])

    def test_is_deterministic(self):
        page = IndexPage()
        assert page.render([_entry()]) == page.render([_entry()])


class TestGeneratedMarker:
    def test_rendered_page_is_recognised(self, tmp_path):
        target = tmp_path / "index.html"
        target.write_text(IndexPage().render([]), encoding="utf-8")
        assert IndexPage.is_generated(target) is True

    def test_hand_made_page_is_not(self, tmp_path):
        target = tmp_path / "index.html"
        target.write_text("<html>mine</html>\n", encoding="utf-8")
        assert IndexPage.is_generated(target) is False

    def test_marker_after_the_first_line_does_not_count(self, tmp_path):
        target = tmp_path / "index.html"
        target.write_text("<html>\n<!-- generated by podcastify -->\n", encoding="utf-8")
        assert IndexPage.is_generated(target) is False

    def test_missing_file_is_not(self, tmp_path):
        assert IndexPage.is_generated(tmp_path / "index.html") is False

    def test_binary_file_is_not(self, tmp_path):
        target = tmp_path / "index.html"
        target.write_bytes(b"\xff\xfe\x00\x00")
        assert IndexPage.is_generated(target) is False

    def test_empty_file_is_not(self, tmp_path):
        target = tmp_path / "index.html"
        target.write_text("", encoding="utf-8")
        assert IndexPage.is_generated(target) is False


class TestRemoveGenerated:
    def test_removes_a_generated_page(self, tmp_path):
        target = tmp_path / "index.html"
        target.write_text(IndexPage().render([]), encoding="utf-8")
        assert IndexPage.remove_generated(target) is True
        assert not target.exists()

    def test_keeps_a_hand_made_page(self, tmp_path):
        target = tmp_path / "index.html"
        target.write_text("<html>mine</html>\n", encoding="utf-8")
        assert IndexPage.remove_generated(target) is False
        assert target.read_text(encoding="utf-8") == "<html>mine</html>\n"

    def test_missing_file_is_a_no_op(self, tmp_path):
        assert IndexPage.remove_generated(tmp_path / "index.html") is False

    def test_failed_unlink_is_logged_not_raised(self, tmp_path, mocker, caplog):
        target = tmp_path / "index.html"
        target.write_text(IndexPage().render([]), encoding="utf-8")
        mocker.patch("pathlib.Path.unlink", side_effect=PermissionError("denied"))
        assert IndexPage.remove_generated(target) is False
        assert any("Could not remove" in r.message for r in caplog.records)


@pytest.mark.parametrize("count, text", [(0, "0 episodes"), (2, "2 episodes")])
def test_plural_forms(count, text):
    assert text in IndexPage().render([_entry(episodes=count)])
