#!/usr/bin/env python3
"""PodcastProcessor writes, keeps and removes public/index.html."""

import os
import re
from datetime import datetime, timezone

import pytest
import yaml

from podcastify.cli import FeedWatcher, PodcastProcessor
from podcastify.index import IndexPage

MARKER = "<!-- generated by podcastify -->"


@pytest.fixture
def roots(golden_roots, monkeypatch):
    monkeypatch.setattr("podcastify.config.Config.PUBLISH_XML", True)
    monkeypatch.setattr("podcastify.config.Config.PUBLISH_INDEX", True)
    return golden_roots


def _show(roots, name, title=None, episodes=1, **extra):
    podcasts, public = roots
    config = {"title": title or name.title(), "description": "D", **extra}
    (podcasts / f"{name}-podcast.yaml").write_text(yaml.safe_dump(config), encoding="utf-8")
    media = public / name
    media.mkdir(exist_ok=True)
    for index in range(episodes):
        (media / f"ep{index}.mp3").write_bytes(b"\x00" * 64)


def _index(roots):
    return (roots[1] / "index.html").read_text(encoding="utf-8")


class TestPublishing:
    def test_writes_the_index_with_the_feeds(self, roots):
        _show(roots, "alpha", title="Alpha Show", episodes=2)
        assert PodcastProcessor().process_all_podcasts() == 0
        html = _index(roots)
        assert html.splitlines()[0] == MARKER
        assert "<h2>Alpha Show</h2>" in html
        assert 'href="http://localhost:8080/alpha.xml"' in html
        assert "2 episodes" in html

    def test_off_by_default_writes_nothing(self, roots, monkeypatch):
        monkeypatch.setattr("podcastify.config.Config.PUBLISH_INDEX", False)
        _show(roots, "alpha")
        PodcastProcessor().process_all_podcasts()
        assert not (roots[1] / "index.html").exists()

    def test_unlisted_feed_is_left_out_but_still_published(self, roots):
        _show(roots, "alpha")
        _show(roots, "hidden", listed=False)
        PodcastProcessor().process_all_podcasts()
        assert "alpha.xml" in _index(roots)
        assert "hidden" not in _index(roots).lower()
        assert (roots[1] / "hidden.xml").exists()

    def test_failed_feed_is_not_listed(self, roots):
        _show(roots, "alpha")
        (roots[0] / "broken-podcast.yaml").write_text("title: Broken\n", encoding="utf-8")
        assert PodcastProcessor().process_all_podcasts() == 1
        assert "broken" not in _index(roots).lower()

    def test_feeds_are_listed_by_title(self, roots):
        _show(roots, "a-last", title="Zulu")
        _show(roots, "z-first", title="Alpha")
        PodcastProcessor().process_all_podcasts()
        html = _index(roots)
        assert html.index("Alpha") < html.index("Zulu")

    def test_all_feeds_unlisted_gives_the_empty_state(self, roots):
        _show(roots, "hidden", listed=False)
        PodcastProcessor().process_all_podcasts()
        assert 'class="empty"' in _index(roots)

    def test_no_configs_gives_the_empty_state(self, roots):
        assert PodcastProcessor().process_all_podcasts() == 0
        assert 'class="empty"' in _index(roots)

    def test_no_configs_and_a_failing_write_is_a_failure(self, roots, mocker):
        mocker.patch("podcastify.cli.os.replace", side_effect=OSError("disk gone"))
        assert PodcastProcessor().process_all_podcasts() == 1

    def test_cover_image_is_shown(self, roots):
        _show(roots, "alpha", image="cover.jpg")
        (roots[1] / "alpha" / "cover.jpg").write_bytes(b"\xff")
        PodcastProcessor().process_all_podcasts()
        assert '<img src="http://localhost:8080/alpha/cover.jpg"' in _index(roots)

    def test_missing_cover_file_is_left_out(self, roots):
        _show(roots, "alpha", image="cover.jpg")
        PodcastProcessor().process_all_podcasts()
        assert "<img" not in _index(roots)

    def test_hostile_title_is_escaped_in_the_written_file(self, roots):
        _show(roots, "alpha", title="<script>x</script> & co")
        PodcastProcessor().process_all_podcasts()
        assert "<script" not in _index(roots)
        assert "&lt;script&gt;x&lt;/script&gt; &amp; co" in _index(roots)

    def test_file_is_world_readable(self, roots):
        _show(roots, "alpha")
        PodcastProcessor().process_all_podcasts()
        assert (roots[1] / "index.html").stat().st_mode & 0o777 == 0o644

    def test_does_not_overwrite_a_hand_made_page(self, roots, caplog):
        _show(roots, "alpha")
        (roots[1] / "index.html").write_text("<html>mine</html>\n", encoding="utf-8")
        PodcastProcessor().process_all_podcasts()
        assert _index(roots) == "<html>mine</html>\n"
        assert any(r.levelname == "WARNING" and "index.html" in r.message for r in caplog.records)

    def test_missing_public_root_writes_nothing_and_does_not_fail(self, tmp_path, monkeypatch):
        monkeypatch.setattr("podcastify.config.Config.PODCASTS_ROOT", tmp_path / "none")
        monkeypatch.setattr("podcastify.config.Config.PUBLIC_ROOT", tmp_path / "nowhere")
        monkeypatch.setattr("podcastify.config.Config.PUBLISH_INDEX", True)
        assert PodcastProcessor().process_all_podcasts() == 0
        assert not (tmp_path / "nowhere").exists()


class TestAtomicWrite:
    def test_uses_a_hidden_temp_file_that_the_stale_sweep_covers(self, roots, mocker):
        _show(roots, "alpha")
        seen = []
        real_replace = os.replace

        def spy(src, dst):
            if str(dst).endswith("index.html"):
                seen.append(os.path.basename(src))
            real_replace(src, dst)

        mocker.patch("podcastify.cli.os.replace", side_effect=spy)
        PodcastProcessor().process_all_podcasts()
        assert len(seen) == 1
        assert seen[0].startswith(".index.")
        assert seen[0].endswith(PodcastProcessor.TEMP_SUFFIX)
        assert not [p for p in roots[1].iterdir() if p.name.endswith(".tmp")]

    def test_temp_file_removed_and_failure_counted_when_replace_fails(self, roots, mocker, caplog):
        _show(roots, "alpha")
        real_replace = os.replace

        def flaky(src, dst):
            if str(dst).endswith("index.html"):
                raise OSError("disk gone")
            real_replace(src, dst)

        mocker.patch("podcastify.cli.os.replace", side_effect=flaky)
        assert PodcastProcessor().process_all_podcasts() == 1
        assert any(r.levelname == "ERROR" and "disk gone" in r.message for r in caplog.records)
        assert (roots[1] / "alpha.xml").exists()
        assert not [p for p in roots[1].iterdir() if p.name.endswith(".tmp")]
        assert not (roots[1] / "index.html").exists()


class TestUnchangedContent:
    def _clock(self, mocker, *moments):
        class SteppingDatetime(datetime):
            ticks = iter(moments)

            @classmethod
            def now(cls, tz=None):
                return next(cls.ticks)

        mocker.patch("podcastify.rss.datetime", SteppingDatetime)

    def test_second_run_keeps_the_file_and_its_mtime(self, roots, mocker):
        _show(roots, "alpha")
        self._clock(mocker, datetime(2030, 1, 1, tzinfo=timezone.utc), datetime(2030, 1, 2, tzinfo=timezone.utc))
        PodcastProcessor().process_all_podcasts()
        index = roots[1] / "index.html"
        os.utime(index, (1_000_000_000, 1_000_000_000))
        before = index.stat()
        PodcastProcessor().process_all_podcasts()
        after = index.stat()
        assert (after.st_ino, after.st_mtime_ns) == (before.st_ino, before.st_mtime_ns)

    def test_build_date_comes_from_the_feed_that_was_kept(self, roots, mocker):
        _show(roots, "alpha")
        self._clock(mocker, datetime(2030, 1, 1, tzinfo=timezone.utc), datetime(2030, 1, 2, tzinfo=timezone.utc))
        PodcastProcessor().process_all_podcasts()
        PodcastProcessor().process_all_podcasts()
        assert "2030-01-01" in _index(roots)
        assert "2030-01-02" not in _index(roots)

    def test_new_feed_publish_updates_the_build_date(self, roots, mocker):
        _show(roots, "alpha")
        self._clock(mocker, datetime(2030, 1, 1, tzinfo=timezone.utc), datetime(2030, 1, 2, tzinfo=timezone.utc))
        PodcastProcessor().process_all_podcasts()
        _show(roots, "alpha", episodes=2)
        PodcastProcessor().process_all_podcasts()
        assert "2030-01-02" in _index(roots)
        assert "2 episodes" in _index(roots)

    def test_changed_listing_rewrites_the_file(self, roots):
        _show(roots, "alpha")
        PodcastProcessor().process_all_podcasts()
        _show(roots, "bravo")
        PodcastProcessor().process_all_podcasts()
        assert "bravo.xml" in _index(roots)

    def test_watcher_regeneration_without_changes_does_not_touch_the_index(self, roots):
        _show(roots, "alpha")
        PodcastProcessor().process_all_podcasts()
        index = roots[1] / "index.html"
        before = index.stat().st_mtime_ns
        watcher = FeedWatcher(PodcastProcessor(), interval=1, initial_run=True)
        assert watcher.check() == 0
        assert index.stat().st_mtime_ns == before

    def test_watcher_picks_up_a_new_feed(self, roots):
        _show(roots, "alpha")
        watcher = FeedWatcher(PodcastProcessor(), interval=1, initial_run=True)
        watcher.check()
        _show(roots, "bravo")
        watcher.check()
        assert "bravo.xml" in _index(roots)


class TestRemoval:
    def test_turning_the_index_off_removes_a_generated_page(self, roots, monkeypatch):
        _show(roots, "alpha")
        PodcastProcessor().process_all_podcasts()
        monkeypatch.setattr("podcastify.config.Config.PUBLISH_INDEX", False)
        PodcastProcessor().process_all_podcasts()
        assert not (roots[1] / "index.html").exists()

    def test_hand_made_page_survives(self, roots, monkeypatch):
        _show(roots, "alpha")
        (roots[1] / "index.html").write_text("<html>mine</html>\n", encoding="utf-8")
        monkeypatch.setattr("podcastify.config.Config.PUBLISH_INDEX", False)
        PodcastProcessor().process_all_podcasts()
        assert _index(roots) == "<html>mine</html>\n"

    def test_removal_happens_with_no_configs_too(self, roots, monkeypatch):
        (roots[1] / "index.html").write_text(IndexPage().render([]), encoding="utf-8")
        monkeypatch.setattr("podcastify.config.Config.PUBLISH_INDEX", False)
        PodcastProcessor().process_all_podcasts()
        assert not (roots[1] / "index.html").exists()


class TestNothingIsWrittenWhenNotPublishing:
    def test_dry_run_writes_nothing(self, roots):
        _show(roots, "alpha")
        PodcastProcessor(dry_run=True).process_all_podcasts()
        assert not (roots[1] / "index.html").exists()

    def test_dry_run_removes_nothing(self, roots, monkeypatch):
        (roots[1] / "index.html").write_text(IndexPage().render([]), encoding="utf-8")
        monkeypatch.setattr("podcastify.config.Config.PUBLISH_INDEX", False)
        PodcastProcessor(dry_run=True).process_all_podcasts()
        assert (roots[1] / "index.html").exists()

    def test_xml_off_writes_nothing(self, roots, monkeypatch):
        monkeypatch.setattr("podcastify.config.Config.PUBLISH_XML", False)
        _show(roots, "alpha")
        PodcastProcessor().process_all_podcasts()
        assert not (roots[1] / "index.html").exists()

    def test_xml_off_removes_nothing(self, roots, monkeypatch):
        (roots[1] / "index.html").write_text(IndexPage().render([]), encoding="utf-8")
        monkeypatch.setattr("podcastify.config.Config.PUBLISH_XML", False)
        monkeypatch.setattr("podcastify.config.Config.PUBLISH_INDEX", False)
        PodcastProcessor().process_all_podcasts()
        assert (roots[1] / "index.html").exists()

    def test_single_podcast_call_does_not_write_the_index(self, roots):
        _show(roots, "alpha")
        PodcastProcessor().process_podcast("alpha", roots[0] / "alpha-podcast.yaml")
        assert not (roots[1] / "index.html").exists()

    def test_feed_build_date_regex_is_not_confused_by_titles(self, roots):
        _show(roots, "alpha", title="<lastBuildDate>x</lastBuildDate>")
        PodcastProcessor().process_all_podcasts()
        assert re.search(r"\d{4}-\d{2}-\d{2}", _index(roots))
