import logging
from dataclasses import dataclass
from datetime import datetime
from html import escape
from pathlib import Path
from typing import List, Optional, Sequence
from urllib.parse import quote

from podcastify.config import Config

logger = logging.getLogger(__name__)

_STYLE = """\
:root { color-scheme: light dark; --bg: #fafafa; --fg: #1a1a1a; --muted: #5c5c5c; --line: #d8d8d8; --link: #0b57d0; }
@media (prefers-color-scheme: dark) {
  :root { --bg: #121212; --fg: #ececec; --muted: #a0a0a0; --line: #333; --link: #8ab4f8; }
}
body { margin: 0; background: var(--bg); color: var(--fg); font: 1rem/1.5 system-ui, sans-serif; }
main { max-width: 42rem; margin: 0 auto; padding: 2rem 1rem; }
h1 { margin: 0 0 1.5rem; font-size: 1.75rem; }
h2 { margin: 0; font-size: 1.15rem; }
ul { list-style: none; margin: 0; padding: 0; }
li { display: flex; gap: 1rem; padding: 1rem 0; border-top: 1px solid var(--line); }
img { width: 4.5rem; height: 4.5rem; border-radius: 0.5rem; object-fit: cover; flex: none; }
p { margin: 0.25rem 0 0; overflow-wrap: anywhere; }
a { color: var(--link); }
.meta, .empty { color: var(--muted); }
"""


@dataclass(frozen=True)
class IndexEntry:
    name: str
    title: str
    episode_count: int
    built: Optional[datetime]
    image: Optional[str]


class IndexPage:
    FILENAME = "index.html"
    MARKER = "<!-- generated by podcastify -->"

    @staticmethod
    def feed_url(name: str) -> str:
        return f"{Config.BASE_URL}/{quote(name)}.xml"

    @classmethod
    def is_generated(cls, path: Path) -> bool:
        try:
            with path.open("r", encoding="utf-8") as f:
                return f.readline().rstrip("\r\n") == cls.MARKER
        except (OSError, UnicodeDecodeError):
            return False

    @classmethod
    def remove_generated(cls, path: Path) -> bool:
        if not cls.is_generated(path):
            return False
        try:
            path.unlink()
        except OSError as e:
            logger.warning(f"Could not remove {path.name}: {e}")
            return False
        return True

    @staticmethod
    def _count(episodes: int) -> str:
        return f"{episodes} episode" if episodes == 1 else f"{episodes} episodes"

    def _item(self, entry: IndexEntry) -> str:
        url = escape(self.feed_url(entry.name))
        meta = self._count(entry.episode_count)
        if entry.built is not None:
            meta += f', last build <time datetime="{entry.built.isoformat()}">{entry.built.strftime("%Y-%m-%d")}</time>'
        cover = f'<img src="{escape(entry.image)}" alt="" loading="lazy">\n' if entry.image else ""
        return (
            f"<li>\n{cover}<div>\n<h2>{escape(entry.title)}</h2>\n"
            f'<p><a href="{url}">{url}</a></p>\n<p class="meta">{meta}</p>\n</div>\n</li>\n'
        )

    def render(self, entries: Sequence[IndexEntry]) -> str:
        ordered: List[IndexEntry] = sorted(entries, key=lambda entry: (entry.title.casefold(), entry.name))
        if ordered:
            body = "<ul>\n" + "".join(self._item(entry) for entry in ordered) + "</ul>\n"
        else:
            body = '<p class="empty">No feeds are listed yet.</p>\n'
        return (
            f"{self.MARKER}\n<!DOCTYPE html>\n"
            '<html lang="en">\n<head>\n<meta charset="utf-8">\n'
            '<meta name="viewport" content="width=device-width, initial-scale=1">\n'
            f"<title>Podcasts</title>\n<style>\n{_STYLE}</style>\n</head>\n"
            f"<body>\n<main>\n<h1>Podcasts</h1>\n{body}</main>\n</body>\n</html>\n"
        )
